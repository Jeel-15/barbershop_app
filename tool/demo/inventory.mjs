// Lists, for every screen file of the app, what a person can SEE and DO there:
// words on screen, buttons, chips, tabs, menu entries, sheets/dialogs/pickers, icons
// and sideways scrollers. It reads the Dart source, so nothing the app shows can be
// forgotten by the demo tour. Run:  node tool/demo/inventory.mjs > docs/DEMO_INVENTORY.md
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const libDir = join(root, 'lib');

function walk(dir, out = []) {
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (p.endsWith('.dart')) out.push(p);
  }
  return out;
}

const files = walk(libDir).filter((f) => {
  const r = relative(libDir, f).replaceAll('\\', '/');
  return (
    /\/presentation\//.test(r) ||
    r.startsWith('features/shell/') ||
    r.startsWith('features/home/') ||
    r.startsWith('features/calendar/presentation/')
  ) && !r.startsWith('features/dev/') && !r.includes('/domain/') && !r.includes('/data/');
});

const strRe = /'((?:[^'\\]|\\.)*)'|"((?:[^"\\]|\\.)*)"/g;
const uiLine =
  /(label|title|subtitle|hint|hintText|emptyTitle|emptyMessage|countLabel|message|caption|actionLabel|confirmLabel|helper|footer|name)\s*:|Text\(|ChipOption\(|KvLine\(|_Line\(|SectionHeader|ErrorState|EmptyState|\('[a-z_]+',\s*'[^']+',\s*(true|false)\)|Semantics\(/;
const noise =
  /^(package:|dart:|assets\/|\/app|\/api|[a-z]+(_[a-z0-9]+)+$|[A-Za-z]+\.[a-z]+$|#|\d+$|%|\s*$)/;

const sheetRe =
  /(showAppSheet|showModalBottomSheet|showDialog|showConfirm|showDatePicker|showTimePicker|showDateRangePicker|showMenu|PopupMenuButton|showToast|showUndoSnack|showSharePdf|Printing\.|Share\.)/g;
const scrollRe =
  /(scrollDirection:\s*Axis\.horizontal|ChipsRow|DateStrip|PageView|SingleChildScrollView\([^)]*horizontal|horizontal|ListView\.separated\([^)]*horizontal|AppSegmented|Tab(Bar)?\b)/;
const iconRe = /Icons\.([a-z0-9_]+)/g;

function strings(text) {
  const out = [];
  let m;
  strRe.lastIndex = 0;
  while ((m = strRe.exec(text))) {
    const s = (m[1] ?? m[2] ?? '').replaceAll("\\'", "'");
    if (s.length < 2 || s.length > 90) continue;
    if (!/[A-Za-z]/.test(s)) continue;
    if (noise.test(s)) continue;
    if (/^\$\{?[a-z]/.test(s) && !/\s/.test(s)) continue;
    out.push(s);
  }
  return out;
}

const out = [];
out.push('# App inventory (generated by tool/demo/inventory.mjs)\n');
out.push(
  'Every screen file, with the words, controls, sheets and sideways scrollers found in its source. ' +
    'The demo tour must cover each item (see DEMO_COVERAGE_PLAN.md).\n',
);

for (const f of files.sort()) {
  const rel = relative(root, f).replaceAll('\\', '/');
  const src = readFileSync(f, 'utf8');
  const lines = src.split('\n');
  const words = new Set();
  const sheets = new Set();
  const scrollers = new Set();
  const icons = new Set();
  const classes = [...src.matchAll(/^class (\w+) extends (\w+)/gm)].map((m) => `${m[1]}`);
  for (let i = 0; i < lines.length; i++) {
    let l = lines[i];
    if (/^\s*(import|export|part) /.test(l) || /^\s*\/\//.test(l)) continue;
    if (/Text\($/.test(l.trim()) && lines[i + 1]) l += ' ' + lines[i + 1];
    if (uiLine.test(l)) for (const s of strings(l)) words.add(s);
    for (const m of l.matchAll(sheetRe)) sheets.add(m[1]);
    if (scrollRe.test(l)) scrollers.add(l.trim().slice(0, 90));
    for (const m of l.matchAll(iconRe)) icons.add(m[1]);
  }
  if (!words.size && !sheets.size) continue;
  out.push(`\n## ${rel}`);
  if (classes.length) out.push(`classes: ${classes.join(', ')}`);
  if (words.size) out.push(`words: ${[...words].map((w) => JSON.stringify(w)).join(' | ')}`);
  if (sheets.size) out.push(`sheets/dialogs/menus: ${[...sheets].join(', ')}`);
  if (scrollers.size) out.push(`scrollers/tabs:\n  - ${[...scrollers].join('\n  - ')}`);
  if (icons.size) out.push(`icons: ${[...icons].join(', ')}`);
}
